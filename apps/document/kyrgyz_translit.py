"""
Модуль транслитерации кыргызских и русских имен в латиницу для ЦНСВ.

Правило соответствия специфических букв кыргызского алфавита:
Ңң — Ññ
Үү — Üü
Өө — Öö
"""

KYRGYZ_TRANSLIT_TABLE = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'yo', 'ж': 'zh', 'з': 'z',
    'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r',
    'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'shch',
    'ы': 'y', 'э': 'e', 'ю': 'yu', 'я': 'ya', 'ъ': '', 'ь': '',
    'А': 'A', 'Б': 'B', 'В': 'V', 'Г': 'G', 'Д': 'D', 'Е': 'E', 'Ё': 'Yo', 'Ж': 'Zh', 'З': 'Z',
    'И': 'I', 'Й': 'Y', 'К': 'K', 'Л': 'L', 'М': 'M', 'Н': 'N', 'О': 'O', 'П': 'P', 'Р': 'R',
    'С': 'S', 'Т': 'T', 'У': 'U', 'Ф': 'F', 'Х': 'Kh', 'Ц': 'Ts', 'Ч': 'Ch', 'Ш': 'Sh', 'Щ': 'Shch',
    'Ы': 'Y', 'Э': 'E', 'Ю': 'Yu', 'Я': 'Ya', 'Ъ': '', 'Ь': '',
    # Кыргызские специфические буквы
    'ө': 'ö', 'Ө': 'Ö',
    'ү': 'ü', 'Ү': 'Ü',
    'ң': 'ñ', 'Ң': 'Ñ'
}


def transliterate_kyrgyz(text: str) -> str:
    """Транслитерирует текст с кыргызского/русского на латиницу с сохранением ñ, ü, ö."""
    if not text:
        return ''
    return "".join(KYRGYZ_TRANSLIT_TABLE.get(char, char) for char in text)


def transliterate_kyrgyz_ascii(text: str) -> str:
    """
    Транслитерирует в чистый ASCII (для безопасных имен файлов, совместимых со старыми плоттерами и CorelDraw):
    ö -> o, ü -> u, ñ -> n.
    """
    latin = transliterate_kyrgyz(text)
    ascii_map = {
        'ö': 'o', 'Ö': 'O',
        'ü': 'u', 'Ү': 'U',
        'ñ': 'n', 'Ñ': 'N',
    }
    return "".join(ascii_map.get(c, c) for c in latin)
