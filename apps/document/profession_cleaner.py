def clean_profession_name(val: Optional[str]) -> str:
    """
    Принимает любую строку профессии (с кавычками, опечатками, капсом или сокращениями)
    и возвращает чистое нормализованное название по госстандарту.
    """
    if not val:
        return ''

    # 1. Снимаем внешние и внутренние кавычки разных типов: ", «, », “ ”
    s = val.strip()
    s = re.sub(r'["«»„“]', '', s)
    s = s.replace("''", '')

    # 2. Убираем лишние пробелы вокруг дефисов и запятых
    s = re.sub(r'\s*-\s*', '-', s)
    s = re.sub(r'\s*,\s*', ', ', s)
    s = re.sub(r'\s+', ' ', s).strip()

    # 3. Нормализация дефисов в разрядах: '3-разряда' -> '3 разряда'
    s = re.sub(r'(\d+)\s*-\s*разряда', r'\1 разряда', s, flags=re.IGNORECASE)
    s = re.sub(r'(\d+)\s*-\s*р\b\.?', r'\1 разряда', s, flags=re.IGNORECASE)
    s = re.sub(r'(\d+)\s*р\b\.?', r'\1 разряда', s, flags=re.IGNORECASE)

    # 4. Проверяем точное соответствие в словаре известных опечаток (регистронезависимо)
    lower_key = s.lower().strip()
    if lower_key in KNOWN_MAPPING:
        return KNOWN_MAPPING[lower_key]

    # Попробуем без дефисов в словах
    lower_normalized = re.sub(r'\s+', ' ', lower_key.replace('-', ' ')).strip()
    if lower_normalized in KNOWN_MAPPING:
        return KNOWN_MAPPING[lower_normalized]

    # 5. Общие правила исправления опечаток на лету (если нет в точном словаре)
    typo_replacements = [
        (r'\bстраительн\w+', 'строительных'),
        (r'\bстраительств\w+', 'строительства'),
        (r'\bстоярн\w+', 'столярного'),
        (r'\bветер[ае]рнарн\w+', 'ветеринарной'),
        (r'\bэлектрообородуван\w+', 'электрооборудования'),
        (r'\bпаотной\b', 'портной'),
        (r'\bпартной\b', 'портной'),
        (r'\bпотрной\b', 'портной'),
        (r'\bпотртной\b', 'портной'),
        (r'\bслесерь\b', 'слесарь'),
        (r'\bслеварь\b', 'слесарь'),
        (r'\bсвнтехник\b', 'сантехник'),
        (r'\bразхряд\w*', 'разряда'),
        (r'\bэлектросврщик\b', 'электросварщик'),
        (r'\bперманентог\w*', 'перманентного'),
        (r'\bовтотранспартн\w+', 'автотранспортных'),
        (r'\bэлектроионтажник\b', 'электромонтажник'),
        (r'\bэлектромонтажнтк\b', 'электромонтажник'),
        (r'^электромотор\b', 'Электромонтер'),
        (r'\bWeb-сайт', 'web-сайт'),
    ]

    for pattern, repl in typo_replacements:
        s = re.sub(pattern, repl, s, flags=re.IGNORECASE)

    # Проверяем снова словарь после замены базовых опечаток
    if s.lower() in KNOWN_MAPPING:
        return KNOWN_MAPPING[s.lower()]

    # 6. Приведение регистра: если сплошной капс или всё строчными — делаем заглавную первую букву
    if s and (s == s.upper() or s == s.lower()):
        # Сохраняем римские цифры I, II, III, IV, V
        words = s.split()
        capitalized_words = []
        for i, word in enumerate(words):
            if word.upper() in ('I', 'II', 'III', 'IV', 'V', 'VI'):
                capitalized_words.append(word.upper())
            elif i == 0:
                capitalized_words.append(word.capitalize())
            else:
                capitalized_words.append(word.lower())
        s = ' '.join(capitalized_words)

    # Гарантируем, что первая буква строки всегда заглавная
    if s:
        s = s[0].upper() + s[1:]

    return s
